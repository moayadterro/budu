const plural = (n: number, one: string, two: string, few: string, many: string) => {
  if (n === 1) return one
  if (n === 2) return two
  const h = n % 100
  if (h >= 3 && h <= 10) return `${n} ${few}`
  return `${n} ${many}`
}

